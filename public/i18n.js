export function createTranslator(lang) {
  const table = DICT[lang] || DICT.fr;
  return (key, vars = {}) => {
    const template = table[key] ?? DICT.fr[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
  };
}
